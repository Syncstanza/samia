// Inventory of ayat where the recitation itself could sound like a takbir.
// Writes data/takbir-ayat.json (used by the app) and docs/takbir-ayat.md.
//
//   exact  "الله أكبر" appears word for word inside the ayah
//   close  a phrase within two letters of it ("الله الكبير", "ولتكبروا الله", ...)
//
// Usage: node tools/takbir-inventory.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { buildIndex } from '../src/engine/quran-index.js';
import { normalize } from '../src/engine/normalize.js';
import { align } from '../src/engine/align.js';

const data = JSON.parse(readFileSync(new URL('../data/quran/quran.json', import.meta.url), 'utf8'));
const ix = buildIndex(data);
const T = normalize('الله اكبر');
const L = ix.letters;

const found = new Map(); // ayah index -> {kind, score, at}
for (let p = 0; p + T.length <= L.length; p++) {
  // only start where a candidate could begin: ا or و/ف/ل + ا
  if (L[p] !== 'ا' && L[p] !== 'ك') continue;
  const r = align(T, L, p, p + T.length + 2);
  if (r.norm < 0.75) continue;
  const a = ix.ayahOf[p];
  const kind = L.slice(ix.ayahStart[a], ix.ayahStart[a + 1]).includes(T) ? 'exact' : 'close';
  const prev = found.get(a);
  if (!prev || r.norm > prev.score) found.set(a, { kind, score: +r.norm.toFixed(2), at: p - ix.ayahStart[a] });
}

// Related: "الله" right next to a word from the root ك-ب-ر (أكبر، الكبير،
// كبّروا، تكبيرا). Not as close in sound, but an imam's takbir is the same words.
for (let a = 0; a < ix.count; a++) {
  if (found.has(a)) continue;
  const words = data.ayat[a][2].split(' ').map(normalize);
  for (let k = 0; k < words.length; k++) {
    if (!/كبر|كبير/.test(words[k])) continue;
    const near = words.slice(Math.max(0, k - 2), k + 3).some((w) => /^(و|ف|ل|ب)?(ا)?لله$|^الله|لله$/.test(w));
    if (!near) continue;
    let at = 0;
    for (let j = 0; j < k; j++) at += words[j].length;
    found.set(a, { kind: 'related', score: 0, at: Math.max(0, at - 6) });
    break;
  }
}

// Ayat with takbir words but no "الله" right next to them (checked by hand).
const MANUAL = [
  [17, 111], // وَكَبِّرْهُ تَكْبِيرًۢا
  [74, 3],   // وَرَبَّكَ فَكَبِّرْ
  [13, 9],   // ٱلْكَبِيرُ ٱلْمُتَعَالِ
  [22, 62], [31, 30], [34, 23], // ٱلْعَلِىُّ ٱلْكَبِيرُ
  [4, 34],   // عَلِيًّا كَبِيرًا
];
for (const [s, n] of MANUAL) {
  const a = ix.indexOf(s, n);
  if (!found.has(a)) found.set(a, { kind: 'related', score: 0, at: 0 });
}

const list = [...found.entries()].sort((x, y) => x[0] - y[0]).map(([a, f]) => {
  const [s, n, ar, en] = data.ayat[a];
  const words = ar.split(' ');
  // the words around the match, for the document
  let acc = 0, w0 = 0;
  for (let k = 0; k < words.length; k++) { if (acc + normalize(words[k]).length > f.at) { w0 = k; break; } acc += normalize(words[k]).length; }
  return { surah: s, ayah: n, kind: f.kind, score: f.score, phrase: words.slice(w0, w0 + 3).join(' ') };
});

writeFileSync(new URL('../data/takbir-ayat.json', import.meta.url), JSON.stringify({
  note: 'Ayat whose recitation contains "الله أكبر" (exact) or a phrase that sounds close to it (close). Generated by tools/takbir-inventory.mjs.',
  ayat: list.map(({ surah, ayah, kind }) => [surah, ayah, kind]),
}, null, 1));

const name = (s) => data.surahs[s - 1].translit;
let md = `# Ayat that sound like a takbir\n\nGenerated by \`tools/takbir-inventory.mjs\` from the Tanzil text. Sami'a double-checks any takbir heard while the imam is in one of these ayat (or the ayah before), so the recitation is never taken for ruku' or sujood.\n\n`;
const TITLES = {
  exact: 'Exact: "الله أكبر" inside the ayah',
  close: 'Close: sounds within two letters of "الله أكبر"',
  related: 'Related: "الله" next to a word from ك-ب-ر (أكبر، الكبير، كبّروا)',
};
for (const kind of ['exact', 'close', 'related']) {
  const rows = list.filter((r) => r.kind === kind);
  md += `## ${TITLES[kind]} (${rows.length})\n\n`;
  md += '| Surah | Ayah | Words |\n|---|---|---|\n';
  for (const r of rows) md += `| ${r.surah} ${name(r.surah)} | ${r.ayah} | ${r.phrase} |\n`;
  md += '\n';
}
writeFileSync(new URL('../docs/takbir-ayat.md', import.meta.url), md);
console.log(['exact', 'close', 'related'].map((k) => `${k} ${list.filter((r) => r.kind === k).length}`).join(', '));
for (const r of list) console.log(r.kind, `${r.surah}:${r.ayah}`, r.score, r.phrase);
